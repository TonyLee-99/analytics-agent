"""Trace summary + a text waterfall viewer.

    uv run python -m analytics_agent.trace_report                 # results/trace_summary.md
    uv run python -m analytics_agent.trace_report --show <trace_id>
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict

from analytics_agent.config import RESULTS, TRACES


def _iter():
    for p in sorted(TRACES.glob("*.jsonl")):
        for line in open(p):
            if line.strip():
                yield p.stem, json.loads(line)


def _step(name: str) -> str:
    return "llm.correct" if name.startswith("llm.correct") else name


def summary() -> str:
    by_file: dict = defaultdict(lambda: {"n": 0, "time": defaultdict(float), "cost": defaultdict(float),
                                         "count": defaultdict(int), "status": defaultdict(int)})
    for stem, t in _iter():
        agg = by_file[stem]
        agg["n"] += 1
        agg["status"][t.get("status", "?")] += 1
        for s in t["spans"]:
            k = _step(s["name"])
            agg["count"][k] += 1
            llm = s.get("llm")
            agg["time"][k] += llm["latency_s"] if llm else s["duration_s"]  # LLM time = original call latency
            agg["cost"][k] += llm.get("cost_usd", 0.0) if llm else 0.0
    lines = ["# Trace summary", "", "Generated by `uv run python -m analytics_agent.trace_report` from `traces/*.jsonl` "
             "(one trace per question, one span per agent step). LLM span time is the original call latency "
             "(cache hits keep the latency of the call that produced them).", ""]
    for stem, agg in sorted(by_file.items()):
        tot_t = sum(agg["time"].values()) or 1.0
        tot_c = sum(agg["cost"].values()) or 1.0
        lines += [f"## {stem}  ({agg['n']} traces; status {dict(agg['status'])})", "",
                  "| step | spans | spans/trace | share of time | share of cost |", "|---|---|---|---|---|"]
        for k in sorted(agg["count"], key=lambda x: -agg["time"][x]):
            lines.append(f"| {k} | {agg['count'][k]} | {agg['count'][k] / agg['n']:.2f} | "
                         f"{100 * agg['time'][k] / tot_t:.1f}% | {100 * agg['cost'][k] / tot_c:.1f}% |")
        lines.append("")
    out = "\n".join(lines)
    (RESULTS / "trace_summary.md").write_text(out)
    return out


def show(trace_id: str) -> str:
    for _stem, t in _iter():
        if t["trace_id"] == trace_id:
            t0 = t["start"]
            rows = [f"trace {trace_id}  [{t.get('config')}] {t['question'][:90]}", f"status={t.get('status')} "
                    f"totals={t['totals']}"]
            for s in t["spans"]:
                llm = s.get("llm") or {}
                dur = llm.get("latency_s", s["duration_s"])
                bar = "#" * max(1, int(dur * 2))
                extra = f" tok={llm.get('input_tokens', 0)}/{llm.get('output_tokens', 0)} ${llm.get('cost_usd', 0):.4f}" \
                    if llm else ""
                rows.append(f"  +{s['start'] - t0:6.2f}s {s['name']:<14} {dur:6.2f}s {bar}{extra}")
            return "\n".join(rows)
    return f"trace {trace_id} not found"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--show", default=None)
    a = ap.parse_args()
    print(show(a.show) if a.show else summary())
